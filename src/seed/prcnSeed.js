// ========== SEED FUNCTION ==========
async function seed() {
  const client = new MongoClient(uri);
  try {
    await client.connect();
    const db = client.db(dbName);

    console.log(`Connected to database "${dbName}"`);

    // ---- USERS ----
    const usersCollection = db.collection('users');
    const existingUsers = await usersCollection.countDocuments();
    if (existingUsers === 0) {
      const result = await usersCollection.insertMany(users, { ordered: false });
      console.log(`✅ Inserted ${result.insertedCount} users.`);
    } else {
      console.log(`⏭️ Users collection already has ${existingUsers} documents. Skipping.`);
    }

    // ---- WALLETS ----
    const walletsCollection = db.collection('wallets');
    const existingWallets = await walletsCollection.countDocuments();
    if (existingWallets === 0) {
      const result = await walletsCollection.insertMany(wallets, { ordered: false });
      console.log(`✅ Inserted ${result.insertedCount} wallets.`);
    } else {
      console.log(`⏭️ Wallets collection already has ${existingWallets} documents. Skipping.`);
    }

    console.log('🎉 Seeding complete!');
  } catch (error) {
    console.error('❌ Seeding failed:', error);
  } finally {
    await client.close();
  }
}

seed();